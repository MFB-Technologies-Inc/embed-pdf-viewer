// The engine-only smoke test: `epdf-uniffi` on the JVM, with the assertions of
// crates/epdf-uniffi/tests/native_surface.rs. It is not published; it keeps
// the engine crate's Kotlin surface checked now that the AAR ships the full
// viewer host instead.
plugins {
    alias(libs.plugins.kotlin.jvm)
}

val repoRoot: File = rootDir.resolve("../../..").canonicalFile
// CARGO_TARGET_DIR as cargo reads it, relative to the workspace when relative.
val cargoTarget: File = (
    System.getenv("CARGO_TARGET_DIR")?.takeIf { it.isNotEmpty() }?.let { repoRoot.resolve(it) }
        ?: repoRoot.resolve("target")
    ).resolve("debug")
val generated = layout.buildDirectory.dir("generated/uniffi/kotlin")
val runtimeSlice = if (System.getProperty("os.arch") == "aarch64") "linux-arm64" else "linux-x64"
val runtimeLibDir: File = (
    System.getenv("PDF_RUNTIME_LIB_DIR")?.takeIf { it.isNotEmpty() }?.let(::File)
        ?: repoRoot.resolve("packages/engine/runtime/build/libpdfium")
    ).resolve("$runtimeSlice/lib")

kotlin {
    jvmToolchain(21)
    compilerOptions {
        jvmTarget = org.jetbrains.kotlin.gradle.dsl.JvmTarget.JVM_17
    }
}

java {
    targetCompatibility = JavaVersion.VERSION_17
}

val buildLinuxEngine = tasks.register<Exec>("buildLinuxEngine") {
    description = "Builds epdf-uniffi and uniffi-bindgen for the host."
    workingDir = repoRoot
    commandLine(
        "cargo", "build", "-p", "epdf-uniffi", "-p", "uniffi-bindgen",
        "--manifest-path", repoRoot.resolve("Cargo.toml").path,
    )
}

// The engine's Kotlin, generated by the repository's own uniffi-bindgen from
// the library the tests load, so the two cannot disagree.
val generateEngineBindings = tasks.register<Exec>("generateEngineBindings") {
    description = "Generates the epdf-uniffi Kotlin bindings."
    dependsOn(buildLinuxEngine)
    val out = generated.get().asFile
    // Regenerated whenever the library or the generator changes.
    inputs.files(cargoTarget.resolve("libepdf_uniffi.so"), cargoTarget.resolve("uniffi-bindgen"))
    outputs.dir(out)
    doFirst { out.deleteRecursively() }
    commandLine(
        cargoTarget.resolve("uniffi-bindgen").path, "generate",
        "--library", cargoTarget.resolve("libepdf_uniffi.so").path,
        "--language", "kotlin", "--no-format", "--out-dir", out.path,
    )
}

sourceSets.test {
    kotlin.srcDir(generateEngineBindings.map { generated.get() })
}

dependencies {
    testImplementation(libs.jna)
    testImplementation(libs.junit)
    testImplementation(libs.json)
    testImplementation(libs.kotlinx.coroutines.core)
}

tasks.test {
    systemProperty("jna.library.path", cargoTarget.path)
    systemProperty("embedpdf.fixtures", repoRoot.resolve("pdfium-multiplatform-prototype/fixtures").path)
    environment("LD_LIBRARY_PATH", runtimeLibDir.path)
    testLogging {
        events("passed", "failed", "skipped")
        exceptionFormat = org.gradle.api.tasks.testing.logging.TestExceptionFormat.FULL
    }
}
